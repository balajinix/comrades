import pandas as pd
import os
import json
from vl_convert import vegalite_to_png
from IPython.display import Image, display

def extract_data(df, col_name):
    """
    Extracts the values from a specific column in a DataFrame as a list.

    Parameters:
        df (pd.DataFrame): The input DataFrame.
        col_name (str): The name of the column to extract.

    Returns:
        list: A list of values from the specified column.
    """
    if col_name in df.columns:
        return df[col_name].tolist()
    else:
        raise ValueError(f"Column '{col_name}' not found in DataFrame.")

def add_data(json_spec, data):
    # look at the number of attributes in the "field" attribute of the "encoding" section of the json_spec
    # the data attribute will haev those many items per object
    n = len(json_spec)
    success = 0

    # if number of data points are < 50 % of the length, then discard the json_spec
    col_names = []
    if "encoding" in json_spec:
        if "x" in json_spec["encoding"]:
            if json_spec["encoding"]["x"]["field"] in data.columns:
                col_names.append(json_spec["encoding"]["x"]["field"])
                success = 1
            else:
                success = -1
        if "y" in json_spec["encoding"]:
            if isinstance(json_spec["encoding"]["y"], list):
                for item in json_spec["encoding"]["y"]:
                    if item["field"] in data.columns:
                        col_names.append(item["field"])
                        success = 1
                    else:
                        success = -1
            else:
                if json_spec["encoding"]["y"]["field"] == "count()":
                    json_spec["encoding"]["y"]["aggregate"] = "count"
                    del json_spec["encoding"]["y"]["field"]
                else:
                    if json_spec["encoding"]["y"]["field"] in data.columns:
                        col_names.append(json_spec["encoding"]["y"]["field"])
                        if (success != -1):
                            success = 1
                    else:
                        success = -1
        if "color" in json_spec["encoding"]:
            if json_spec["encoding"]["color"]["field"] == "count()":
                json_spec["encoding"]["color"]["aggregate"] = "count"
                if (success != -1):
                    success = 1
                del json_spec["encoding"]["color"]["field"]
            else:
                if json_spec["encoding"]["color"]["field"] in data.columns:
                    col_names.append(json_spec["encoding"]["color"]["field"])
                    success = 1
                else:
                    success = -1
    
    if success == -1:
        return []
    data_li = {}
    for i in col_names:
        item_li = extract_data(data, i)
        data_li[i] = item_li

    final_li = []
    num = len(data)

    for i in range(num):
        success = 1
        loc_di = {}
        for col_name in data_li:
            loc_di[col_name] = data_li[col_name][i]
            if data_li[col_name][i] == None or pd.isna(data_li[col_name][i]):
                success = 0
        if success == 1:
            final_li.append(loc_di)

    return final_li

def process_spec(spec_list, data, output_dir):
    final_li_spec = []
    print("The Vega-Lite specifications as generated by the LLM are: ")
    total = len(spec_list)
    error = 0

    for item in spec_list:
        print(item)
        print("-" * 30)

        # Extract the inner Vega-Lite spec
        vegalite_spec = item.get("vegalite_spec", {})

        # Apply the data
        value = add_data(vegalite_spec, data)

        if value == []:
            error += 1

        # Add the data to the spec
        vegalite_spec["data"] = {"values": value}

        # Only keep if data is not empty
        if value != []:
            item["vegalite_spec"] = vegalite_spec  # Update spec with data
            final_li_spec.append(item)

    spec_list_path = os.path.join(output_dir, "spec_li_path.json")
    with open(spec_list_path, "w") as f:
        json.dump(final_li_spec, f)

    return final_li_spec, error, total

def create_vegalite_chart(spec_json, index, output_dir):
    # for each spec, return title, reason and the image_path or error
    """
    Renders a Vega-Lite chart from a JSON spec and saves it as a PNG image.

    Args:
        spec_json (dict): Vega-Lite chart specification.
        output_dir (str): Directory where the image will be saved.
    """
    os.makedirs(output_dir, exist_ok=True)

    # Create a name from the title or fallback
    chart_name = spec_json["vegalite_spec"].get("title", "vega_lite_chart").replace(" ", "_").lower()
    output_path = os.path.join(output_dir, f"{chart_name}_{index}.png")

    try:
        # Convert spec to PNG bytes
        png_bytes = vegalite_to_png(spec_json["vegalite_spec"])
        with open(output_path, "wb") as f:
            f.write(png_bytes)
        print(f"Chart saved to: {output_path}")

        display(Image(filename=output_path))

        result = {
            "type": spec_json["type"],
            "title": spec_json["title"],
            "reason": spec_json["reason"],
            "image_path": output_path
        }

        return result
    except Exception as e:
        print(f"Failed to save chart: {e}")
        return {}