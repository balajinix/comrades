"""Bursty vs independent faults × retry arms × concurrency (coded-workflow arm).

Grid A (correlation): K=1, Bernoulli vs Gilbert–Elliott with mean burst
2/10/60 s, matched marginal rate 0.1/0.3/0.6, every retry arm, 3 seeds.
Grid B (herd): GE mean burst 10 s at rate 0.3, K in {1, 4, 16, 64}, backend
capacity unlimited or 10 req/s, every retry arm, 3 seeds.

Grid C (synchronized onset): every client starts at t=0 into a 10 s outage on
all backends (a backend restart), K in {16, 64, 256}, capacity 10 req/s, 2 min.
This is the classic thundering-herd setting that jitter is designed for.

Writes lab/findings/bursty_faults_{a,b,c}.csv and lab/findings/bursty_faults.md.
Usage: .venv/bin/python experiments/exp_bursty_faults.py
"""
from __future__ import annotations

import csv
import statistics
import time
from pathlib import Path

from dal_lab.faults import Bernoulli, GilbertElliott, Outage
from dal_lab.retry import ARMS
from dal_lab.sim import SimConfig, simulate, summarize

OUT = Path(__file__).resolve().parents[1] / "findings"
SEEDS = (0, 1, 2)
RATES = (0.1, 0.3, 0.6)
BURSTS = (2.0, 10.0, 60.0)
HORIZON = 3600.0


def _process(kind: str, rate: float, burst: float | None, seed: int):
    if kind == "bernoulli":
        return Bernoulli(rate, seed=seed)
    return GilbertElliott.matched(rate, mean_bad=burst, seed=seed)


def _run(row_base: dict, cfg: SimConfig, kind: str, rate: float, burst: float | None,
         seed: int, arm: str) -> dict:
    proc = _process(kind, rate, burst, seed)
    res = simulate(cfg, proc, ARMS[arm])
    return {**row_base, "process": kind, "rate": rate, "mean_burst_s": burst or 0.0,
            "arm": arm, "seed": seed, **summarize(res, cfg, proc)}


def grid_a() -> list[dict]:
    rows = []
    for rate in RATES:
        for kind, burst in [("bernoulli", None)] + [("ge", b) for b in BURSTS]:
            for arm in ARMS:
                for seed in SEEDS:
                    cfg = SimConfig(clients=1, horizon_s=HORIZON, seed=seed)
                    rows.append(_run({"grid": "A", "clients": 1, "capacity_rps": ""},
                                     cfg, kind, rate, burst, seed, arm))
    return rows


def grid_b() -> list[dict]:
    rows = []
    for k in (1, 4, 16, 64):
        for cap in (None, 10.0):
            for arm in ARMS:
                for seed in SEEDS:
                    cfg = SimConfig(clients=k, horizon_s=HORIZON, capacity_rps=cap, seed=seed)
                    rows.append(_run({"grid": "B", "clients": k, "capacity_rps": cap or ""},
                                     cfg, "ge", 0.3, 10.0, seed, arm))
    return rows


def grid_c() -> list[dict]:
    rows = []
    for k in (16, 64, 256):
        for arm in ARMS:
            for seed in SEEDS:
                cfg = SimConfig(clients=k, horizon_s=120.0, capacity_rps=10.0,
                                sync_start=True, seed=seed)
                proc = Outage(0.0, 10.0)
                res = simulate(cfg, proc, ARMS[arm])
                rows.append({"grid": "C", "clients": k, "capacity_rps": 10.0,
                             "process": "outage_0_10", "arm": arm, "seed": seed,
                             **summarize(res, cfg, proc, herd_window_s=30.0)})
    return rows


def _write(rows: list[dict], path: Path) -> None:
    with path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def _agg(rows, keys, metric):
    groups: dict[tuple, list[float]] = {}
    for r in rows:
        groups.setdefault(tuple(r[k] for k in keys), []).append(r[metric])
    return {k: (statistics.mean(v), statistics.pstdev(v)) for k, v in groups.items()}


def report(a: list[dict], b: list[dict], c_rows: list[dict]) -> str:
    arms = list(ARMS)
    lines = ["# Bursty faults: results (coded-workflow arm, virtual time)", "",
             "Generated by `experiments/exp_bursty_faults.py`. Task = 4 calls over 3 "
             "backends, 1 s LLM turn between calls, 0.2 s per call, 60 s deadline, "
             "max 5 attempts per call in every retry arm. Mean ± sd over 3 seeds, 1 h "
             "virtual time each.", ""]
    succ = _agg(a, ("rate", "process", "mean_burst_s", "arm"), "success_rate")
    amp = _agg(a, ("rate", "process", "mean_burst_s", "arm"), "attempts_per_success")
    lat = _agg(a, ("rate", "process", "mean_burst_s", "arm"), "latency_p95_s")
    procs = [("bernoulli", 0.0)] + [("ge", x) for x in BURSTS]
    for rate in RATES:
        lines += [f"## Grid A, marginal fault rate {rate}: task success", "",
                  "| arm | " + " | ".join("indep." if p == "bernoulli" else f"GE {int(t)} s"
                                         for p, t in procs) + " |",
                  "|---|" + "---|" * len(procs)]
        for arm in arms:
            cells = [f"{succ[(rate, p, t, arm)][0]:.2f} ± {succ[(rate, p, t, arm)][1]:.2f}"
                     for p, t in procs]
            lines.append(f"| {arm} | " + " | ".join(cells) + " |")
        lines += ["", f"Calls per successful task (rate {rate}):", "",
                  "| arm | " + " | ".join("indep." if p == "bernoulli" else f"GE {int(t)} s"
                                         for p, t in procs) + " |",
                  "|---|" + "---|" * len(procs)]
        for arm in arms:
            lines.append(f"| {arm} | " + " | ".join(f"{amp[(rate, p, t, arm)][0]:.2f}"
                                                    for p, t in procs) + " |")
        lines += ["", f"p95 latency of successful tasks, s (rate {rate}):", "",
                  "| arm | " + " | ".join("indep." if p == "bernoulli" else f"GE {int(t)} s"
                                         for p, t in procs) + " |",
                  "|---|" + "---|" * len(procs)]
        for arm in arms:
            lines.append(f"| {arm} | " + " | ".join(f"{lat[(rate, p, t, arm)][0]:.1f}"
                                                    for p, t in procs) + " |")
        lines.append("")
    keys = ("clients", "capacity_rps", "arm")
    bs = _agg(b, keys, "success_rate")
    bp = _agg(b, keys, "peak_rps_after_burst")
    bl = _agg(b, keys, "load_faults")
    lines += ["## Grid B: concurrency (GE 10 s bursts, rate 0.3)", "",
              "Success / mean over bursts of the peak 1 s request count in the 15 s after a burst ends / "
              "load-induced 429s (capacity 10 req/s per backend).", "",
              "| arm | " + " | ".join(f"K={k} {'cap' if c else 'no cap'}"
                                     for k in (1, 4, 16, 64) for c in ("", 10.0)) + " |",
              "|---|" + "---|" * 8]
    for arm in arms:
        cells = []
        for k in (1, 4, 16, 64):
            for c in ("", 10.0):
                cells.append(f"{bs[(k, c, arm)][0]:.2f} / {bp[(k, c, arm)][0]:.1f} / "
                             f"{bl[(k, c, arm)][0]:.0f}")
        lines.append(f"| {arm} | " + " | ".join(cells) + " |")
    lines.append("")
    keys = ("clients", "arm")
    cs = _agg(c_rows, keys, "success_rate")
    cp = _agg(c_rows, keys, "peak_rps_after_burst")
    cl = _agg(c_rows, keys, "load_faults")
    ca = _agg(c_rows, keys, "attempts_per_task")
    lines += ["## Grid C: synchronized onset (all clients start into a 10 s outage)", "",
              "Success / peak req/s (max 1 s bin) in the 30 s after recovery / load-induced 429s / "
              "attempts per task. Capacity 10 req/s per backend, 2 min.", "",
              "| arm | K=16 | K=64 | K=256 |", "|---|---|---|---|"]
    for arm in arms:
        lines.append(f"| {arm} | " + " | ".join(
            f"{cs[(k, arm)][0]:.2f} / {cp[(k, arm)][0]:.1f} / {cl[(k, arm)][0]:.0f} / "
            f"{ca[(k, arm)][0]:.1f}" for k in (16, 64, 256)) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    t0 = time.time()
    a = grid_a()
    _write(a, OUT / "bursty_faults_a.csv")
    b = grid_b()
    _write(b, OUT / "bursty_faults_b.csv")
    c = grid_c()
    _write(c, OUT / "bursty_faults_c.csv")
    (OUT / "bursty_faults.md").write_text(report(a, b, c))
    print(f"{len(a)} + {len(b)} + {len(c)} simulations in {time.time() - t0:.1f} s -> {OUT}")


if __name__ == "__main__":
    main()
